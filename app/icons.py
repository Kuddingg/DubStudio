def _svg(name: str, color: str | None, stroke: float = 2.0) -> str:
    if not color:                                # mặc định = màu chữ của chế độ đang dùng
        from .theme import C
        color = C["text"]
    body = _P[name].replace("{c}", color)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" '
        f'stroke="{color}" stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{body}</svg>'
    )


def _dpr() -> float:
    s = QGuiApplication.primaryScreen()
    return s.devicePixelRatio() if s else 1.0


def pixmap(name: str, color: str | None = None, size: int = 18, stroke: float = 2.0) -> QPixmap:
    dpr = _dpr()
    px = max(1, int(size * dpr))
    pm = QPixmap(px, px)
    pm.fill(Qt.transparent)
    renderer = QSvgRenderer(QByteArray(_svg(name, color, stroke).encode()))
    p = QPainter(pm)
    renderer.render(p, QRectF(0, 0, px, px))
    p.end()
    pm.setDevicePixelRatio(dpr)
    return pm


def icon(name: str, color: str | None = None, size: int = 18) -> QIcon:
    ic = QIcon()
    ic.addPixmap(pixmap(name, color, size))
    return ic


def write_file(name: str, color: str, stroke: float = 2.4) -> str:
    """Ghi SVG ra file để dùng trong QSS (url(...))."""
    path = CACHE / f"{name}_{color.strip('#')}.svg"
    path.write_text(_svg(name, color, stroke), encoding="utf-8")
    return path.as_posix()
